  await expect(missing.getByRole("button", { name: "一键导入", exact: true })).toBeDisabled();
  await missing.getByRole("button", { name: "从别处导入", exact: true }).click();
  const replacement = page.getByRole("dialog", { name: "导入素材", exact: true });
