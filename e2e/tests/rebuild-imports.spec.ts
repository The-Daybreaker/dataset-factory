  expect(zip.subarray(0, 4)).toEqual(Buffer.from([0x50, 0x4b, 0x03, 0x04]));
  expect(zip).toEqual(await readFile(path.join(directory, ".dsf", "export", download.suggestedFilename())));
  const source = testInfo.outputPath("source");
  await mkdir(source, { recursive: true });
  await writeFile(path.join(source, "recover.png"), Buffer.concat([await readFile(assetPath), Buffer.from("recover")]));
